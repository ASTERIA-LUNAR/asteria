"""
ASTERIA - named features for the 3D view labels, from the IAU Gazetteer of Planetary Nomenclature (USGS):
MOON_nomenclature_center_pts.zip from https://planetarynames.wr.usgs.gov/GIS_Downloads
(file https://asc-planetarynames-data.s3.us-west-2.amazonaws.com/MOON_nomenclature_center_pts.zip, unzipped to dem/gazetteer/).

For each site with a 3D tile: up to 5 approved features (craters, mountains, ...) whose centre lies within 40 km of the
site, nearest first, excluding a feature centred on the site itself (within 0.5 km). Stored with their Gazetteer centre, diameter,
type, feature page link and the site-grid position (e, n) = azimuthal-equidistant ground coordinates (great-circle
distance and azimuth from the site on the 1737.4 km sphere), the same frame as the terrain.
Output: data/terrain3d/features.js
Usage: .venv/Scripts/python -I tools/features3d.py
"""
import json
import math
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import terrain3d as T3   # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DBF = os.path.join(ROOT, 'dem', 'gazetteer', 'MOON_nomenclature_center_pts.dbf')
R_M = 1737400.0
MAX_KM, MAX_N = 40.0, 5


def read_dbf(path):
    f = open(path, 'rb')
    hdr = f.read(32)
    n, hl, rl = struct.unpack('<I', hdr[4:8])[0], struct.unpack('<H', hdr[8:10])[0], struct.unpack('<H', hdr[10:12])[0]
    fields = []
    while True:
        d = f.read(32)
        if d[0] == 0x0D:
            break
        fields.append((d[:11].split(b'\0')[0].decode(), d[16]))
    f.seek(hl)
    for _ in range(n):
        rec = f.read(rl)
        if rec[0:1] == b'*':
            continue
        out, pos = {}, 1
        for name, ln in fields:
            out[name] = rec[pos:pos + ln].decode('utf-8', 'replace').strip(); pos += ln
        yield out


def dist_az(lat0, lon0, lat, lon):
    p1, p2, dl = math.radians(lat0), math.radians(lat), math.radians(lon - lon0)
    c = math.sin(p1) * math.sin(p2) + math.cos(p1) * math.cos(p2) * math.cos(dl)
    s = math.acos(max(-1, min(1, c))) * R_M
    az = math.atan2(math.sin(dl) * math.cos(p2), math.cos(p1) * math.sin(p2) - math.sin(p1) * math.cos(p2) * math.cos(dl))
    return s, az


def main():
    feats = [r for r in read_dbf(DBF) if r['approval'].lower().startswith('adopted')]
    south = [r for r in feats if float(r['center_lat']) < -75]
    out = {}
    for s in T3.horizon_sites():
        cand = []
        for r in south:
            lat, lon = float(r['center_lat']), float(r['center_lon'])
            if lon > 180:
                lon -= 360
            d, az = dist_az(s['lat'], s['lon'], lat, lon)
            if d > MAX_KM * 1000 or d < 500:   # beyond 40 km, or the site itself (landform-centre sites)
                continue
            cand.append({'name': r['clean_name'], 'type': r['type'], 'lat': round(lat, 4), 'lon': round(lon, 4),
                         'diameter_km': round(float(r['diameter'] or 0), 2), 'link': r['link'].replace('http://', 'https://'),
                         'dist_km': round(d / 1000, 2), 'e': round(d * math.sin(az), 1), 'n': round(d * math.cos(az), 1)})
        cand.sort(key=lambda x: x['dist_km'])
        out[s['id']] = cand[:MAX_N]
        print('%-20s %s' % (s['id'], ', '.join('%s (%s, %.1f km)' % (c['name'], c['type'], c['dist_km']) for c in out[s['id']]) or '-'))
    meta = {'source': 'IAU Gazetteer of Planetary Nomenclature (IAU WGPSN / USGS Astrogeology), MOON_nomenclature_center_pts, https://planetarynames.wr.usgs.gov/GIS_Downloads',
            'note': 'Feature centre coordinates (planetocentric, east longitude) as published; label placed at the centre on the terrain.',
            'generator': 'tools/features3d.py', 'sites': out}
    with open(os.path.join(ROOT, 'data', 'terrain3d', 'features.js'), 'w', encoding='utf-8') as f:
        f.write('// Generated by tools/features3d.py from the IAU Gazetteer of Planetary Nomenclature (USGS)\n')
        f.write('window.ASTERIA_FEATURES3D = %s;\n' % json.dumps(meta))


if __name__ == '__main__':
    main()
