"""
ASTERIA - Earth textures for the 3D view from NASA's Blue Marble Next Generation (topography and bathymetry,
July 2004; cloud-free monthly composite; NASA Earth Observatory, public domain NASA imagery):
https://assets.science.nasa.gov/content/dam/science/esd/eo/images/bmng/bmng-topography-bathymetry/july/world.topo.bathy.200407.3x5400x2700.jpg
(downloaded by tools/fetch_round4.py). Equirectangular, longitude -180..180 left to right, north up.
Writes data/earth/earth_<w>.js (w = 2048, 1024, 512) holding a JPEG as a base64 data URL, because a page opened
from file:// cannot use a separately loaded image file as a WebGL texture.
Usage: .venv/Scripts/python -I tools/earth_texture.py
"""
import base64
import io
import os

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'dem', 'earth', 'world.topo.bathy.200407.3x5400x2700.jpg')
OUT = os.path.join(ROOT, 'data', 'earth')
os.makedirs(OUT, exist_ok=True)
im = Image.open(SRC).convert('RGB')
assert im.size == (5400, 2700)
for w in (2048, 1024, 512):
    buf = io.BytesIO()
    im.resize((w, w // 2), Image.LANCZOS).save(buf, 'JPEG', quality=85, optimize=True)
    b64 = base64.b64encode(buf.getvalue()).decode('ascii')
    with open(os.path.join(OUT, 'earth_%d.js' % w), 'w') as f:
        f.write('// Generated by tools/earth_texture.py from NASA Blue Marble Next Generation (July 2004, cloud-free; public domain NASA imagery)\n')
        f.write('window.ASTERIA_EARTH_TEX = window.ASTERIA_EARTH_TEX || {};\n')
        f.write('window.ASTERIA_EARTH_TEX[%d] = "data:image/jpeg;base64,%s";\n' % (w, b64))
    print(w, len(b64) // 1024, 'KB')
