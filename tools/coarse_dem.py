"""
ASTERIA - compact downsampled south-pole DEM for terrain horizons at clicked map points.

Builds a square grid covering the whole map area (the tile square, +-304 km, about 80S on the axes and
76S in the corners) at a chosen pixel size (default 240 m), as the AREA MEAN of the finest LOLA DEM that
fully covers each coarse pixel:
  LDEM_85S_20M (12 x 12 blocks at 240 m), LDEM_80S_80M (3 x 3), LDEM_75S_120M (2 x 2).
The coarse pixel edges are aligned with the pixel edges of all three DEMs (same polar stereographic grid,
centre -90, lon 0 up, 90E right, R = 1737.4 km), so the block means are exact.

Output: data/dem_coarse.js  (window.LUNA_DEM_COARSE = {meta..., b64: ...})
  heights rounded to whole metres (int16), each row first-differenced (int16 wrap-around), zlib-compressed,
  base64. The browser inflates it with DecompressionStream('deflate') and undoes the differences
  (js/jobs.js). Embedded as .js so it loads under file://.

Usage: .venv/Scripts/python -I tools/coarse_dem.py [pixel_m]      (pixel_m must be a multiple of 240)
       .venv/Scripts/python -I tools/coarse_dem.py check [pixel_m]
           implementation check: horizons with tools/terrain.py's own ray code on the SAME downsampled grid,
           written to dem/work/coarse_py_horizons.json; tests/coarse_validation.js compares them with the
           browser code (js/jobs.js) to show that the JavaScript port reproduces terrain.py.
"""
import base64
import json
import math
import os
import sys
import zlib

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import terrain as T  # noqa: E402

MAP_HALF_M = 304000.0          # data/tiles_meta.js halfExtent_m


def dem_raw(name):
    base = os.path.join(T.DEM_DIR, name)
    L = T.read_label(base + '.lbl')
    n = L['lines']
    mm = np.memmap(base + '.img', dtype='<i2', mode='r', shape=(n, n))
    return mm, n, L['scale'], L['factor'], n / 2 * L['scale']


def build(px):
    k_cells = int(math.ceil(MAP_HALF_M / px))
    half = k_cells * px
    n = 2 * k_cells
    H = np.full((n, n), np.nan, dtype=np.float64)
    src = np.zeros((n, n), dtype=np.uint8)
    used = []
    for code, name in ((3, 'ldem_75s_120m'), (2, 'ldem_80s_80m'), (1, 'ldem_85s_20m')):   # coarse first, finer overwrite
        mm, nd, sc, fac, hd = dem_raw(name)
        kf = px / sc
        assert abs(kf - round(kf)) < 1e-9, 'pixel size must be a multiple of %g m' % sc
        kf = int(round(kf))
        off = (half - hd) / sc                       # DEM pixel index of coarse edge 0 = -off
        assert abs(off - round(off)) < 1e-6, 'grids not aligned for ' + name
        off = int(round(off))
        # coarse cell c spans DEM pixels c*kf - off .. c*kf - off + kf - 1
        c0 = max(0, int(math.ceil(off / kf)))
        c1 = min(n, (nd + off) // kf)                # exclusive
        if c1 <= c0:
            continue
        p0 = c0 * kf - off
        for r in range(c0, c1, 64):                  # strips of coarse rows
            r1 = min(c1, r + 64)
            blk = np.asarray(mm[r * kf - off:r1 * kf - off, p0:p0 + (c1 - c0) * kf], dtype=np.float64)
            m = blk.reshape(r1 - r, kf, c1 - c0, kf).mean(axis=(1, 3)) * fac
            H[r:r1, c0:c1] = m
            src[r:r1, c0:c1] = code
        used.append({'name': name.upper(), 'scale_m': sc, 'blocks': kf, 'cells': [c0, c1]})
        print('%s: coarse cells %d..%d (%d x %d px blocks)' % (name, c0, c1 - 1, kf, kf))
    assert not np.isnan(H).any(), 'coverage gap'
    return H, src, half, n, used


def encode(H):
    q = np.round(H).astype(np.int32)
    assert q.min() > -32768 and q.max() < 32767
    q = q.astype(np.int16)
    d = q.copy()
    d[:, 1:] = (q[:, 1:].astype(np.int32) - q[:, :-1].astype(np.int32)).astype(np.int16)
    raw = d.astype('<i2').tobytes()
    comp = zlib.compress(raw, 9)
    return q, comp


def main():
    px = float(sys.argv[1]) if len(sys.argv) > 1 else 240.0
    H, src, half, n, used = build(px)
    q, comp = encode(H)
    b64 = base64.b64encode(comp).decode('ascii')
    meta = {
        'pixel_m': px, 'n': n, 'halfExtent_m': half, 'encoding': 'int16 metres, row first-differences, zlib, base64',
        'heightRef': 'metres above the 1737.4 km sphere', 'method': 'area mean of the finest LOLA DEM fully covering each pixel',
        'products': used, 'heightRange_m': [int(q.min()), int(q.max())],
        'projection': 'Polar stereographic (spherical R = 1737.4 km), centre -90, lon 0 up, 90E right; pixel (i, j): x = -half + (i + 0.5) * pixel, y = half - (j + 0.5) * pixel',
        'source': 'https://pds-geosciences.wustl.edu/lro/lro-l-lola-3-rdr-v1/lrolol_1xxx/data/lola_gdr/polar/img/',
        'bytesCompressed': len(comp)
    }
    out = os.path.join(T.ROOT, 'data', 'dem_coarse.js')
    with open(out, 'w') as f:
        f.write('// Generated by tools/coarse_dem.py - downsampled LOLA DEM for clicked-point horizons\n')
        f.write('window.LUNA_DEM_COARSE = %s;\n' % json.dumps(dict(meta, b64=b64)))
    np.save(os.path.join(T.DEM_DIR, 'work', 'coarse_%dm.npy' % int(px)), q)
    print('grid %d x %d at %g m, half extent %.0f m; heights %d..%d m; compressed %.2f MB, file %.2f MB' % (
        n, n, px, half, q.min(), q.max(), len(comp) / 1e6, os.path.getsize(out) / 1e6))


class CoarseDEM:
    """The downsampled grid wrapped in terrain.PolarDEM's interface (same bilinear sampling)."""
    def __init__(self, q, px):
        self.name = 'COARSE_%dM' % int(px)
        self.n = q.shape[0]
        self.scale = px
        self.h = q.astype(np.float32)
        self.half_extent = self.n / 2 * px
    ij = T.PolarDEM.ij
    sample = T.PolarDEM.sample


def check(px):
    q = np.load(os.path.join(T.DEM_DIR, 'work', 'coarse_%dm.npy' % int(px)))
    T._DEMS = [CoarseDEM(q, px)]
    out = {}
    for sid, lat, lon in (('im2', -84.7906, 29.1957), ('mons_malapert', -85.98, -1.67), ('peak_shackleton', -88.79, 124.5)):
        e, reach, h0, prod = T.horizon_mask(lat, lon)
        out[sid] = {'lat': lat, 'lon': lon, 'elevations': [float(v) for v in e], 'siteHeight_m': h0}
        print(sid, 'h0 %.1f m, horizon max %.3f deg' % (h0, e.max()))
    with open(os.path.join(T.DEM_DIR, 'work', 'coarse_py_horizons.json'), 'w') as f:
        json.dump(out, f)


if __name__ == '__main__':
    if len(sys.argv) > 1 and sys.argv[1] == 'check':
        check(float(sys.argv[2]) if len(sys.argv) > 2 else 240.0)
    else:
        main()
