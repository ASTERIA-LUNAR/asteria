"""
ASTERIA - star list for the 3D view from the Yale Bright Star Catalogue, 5th revised edition
(Hoffleit & Warren 1991; CDS catalogue V/50, public domain; copy fetched by tools/fetch_round4.py from
http://tdc-www.harvard.edu/catalogs/bsc5.dat.gz).

Keeps every star with V <= 5.0 and a position (novae/non-stellar entries without coordinates are skipped).
Fields (CDS V/50 ReadMe byte positions): HR 1-4, Name 5-14, RA J2000 76-83, Dec J2000 84-90, Vmag 103-107,
B-V 110-114, pmRA 149-154 ("/yr, J2000), pmDE 155-160 ("/yr).
Output: data/stars.js  window.ASTERIA_STARS = { source, fields, rows: [[hr, ra_deg, dec_deg, vmag, bv, pmra_as, pmde_as, name], ...] }
Usage: .venv/Scripts/python -I tools/stars.py
"""
import gzip
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'dem', 'stars', 'bsc5.dat.gz')
VMAX = 5.0


def f(s):
    s = s.strip()
    return float(s) if s else None


def main():
    rows = []
    for line in gzip.open(SRC, 'rt', encoding='latin-1'):
        line = line.rstrip('\n').ljust(197)
        if not line[75:77].strip():
            continue
        v = f(line[102:107])
        if v is None or v > VMAX:
            continue
        ra = (int(line[75:77]) + int(line[77:79]) / 60 + float(line[79:83]) / 3600) * 15
        dec = int(line[84:86]) + int(line[86:88]) / 60 + int(line[88:90]) / 3600
        if line[83] == '-':
            dec = -dec
        bv = f(line[109:114])
        pmra, pmde = f(line[148:154]) or 0.0, f(line[154:160]) or 0.0
        name = ' '.join(line[4:14].split())
        rows.append([int(line[0:4]), round(ra, 5), round(dec, 5), v, bv if bv is not None else 0.6, pmra, pmde, name])
    rows.sort(key=lambda r: r[3])
    out = {
        'source': 'Yale Bright Star Catalogue, 5th revised edition (Hoffleit & Warren 1991), CDS catalogue V/50, public domain; file http://tdc-www.harvard.edu/catalogs/bsc5.dat.gz',
        'fields': ['HR', 'RA_J2000_deg', 'Dec_J2000_deg', 'Vmag', 'B-V', 'pmRA_arcsec_per_yr', 'pmDE_arcsec_per_yr', 'name'],
        'vmax': VMAX, 'generator': 'tools/stars.py', 'rows': rows,
    }
    with open(os.path.join(ROOT, 'data', 'stars.js'), 'w', encoding='utf-8') as fh:
        fh.write('// Generated by tools/stars.py from the Yale Bright Star Catalogue (BSC5, public domain)\n')
        fh.write('window.ASTERIA_STARS = %s;\n' % json.dumps(out, separators=(',', ':')))
    print(len(rows), 'stars with V <=', VMAX, '; brightest:', [r[7] or r[0] for r in rows[:5]])


if __name__ == '__main__':
    main()
