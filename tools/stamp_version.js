/* Writes data/version.js with the git commit the app was built from (the app runs from file:// and cannot ask git).
 * The stamp names the commit that was HEAD when this ran; commit data/version.js right after, so the stamp refers to
 * the parent of the commit that contains it (the code is the same unless something else changed in between).
 *   node tools/stamp_version.js */
'use strict';
const { execSync } = require('child_process'), fs = require('fs'), path = require('path');
const git = c => execSync('git ' + c, { cwd: path.join(__dirname, '..') }).toString().trim();
const commit = git('rev-parse --short HEAD'), branch = git('rev-parse --abbrev-ref HEAD'), date = git('log -1 --format=%cI HEAD');
const v = { commit, branch, commitDate: date, text: `ASTERIA ${branch} @ git ${commit} (${date.slice(0, 10)})` };
fs.writeFileSync(path.join(__dirname, '..', 'data', 'version.js'), '// Generated by tools/stamp_version.js - git commit the app was built from\nwindow.ASTERIA_VERSION = ' + JSON.stringify(v) + ';\n');
console.log(v.text);
