'use strict';
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
function build() {
  const astro = fs.readFileSync(path.join(root, 'lib', 'astronomy.browser.min.js'), 'utf8');
  const engine = fs.readFileSync(path.join(root, 'js', 'engine.js'), 'utf8');
  return '// Generated with Claude Code (Anthropic) under human direction (ASTERIA wrapper; the Astronomy Engine copy is by Don Cross).\n' +
    '// GENERATED by tools/build_core.js - do not edit. Verbatim copies of lib/astronomy.browser.min.js\n' +
    '// (Astronomy Engine 2.1.19, MIT, Don Cross) and js/engine.js, wrapped so a Web Worker can reuse the source.\n' +
    'window.ASTERIA_CORE = function () {\n' + astro + '\n;\n' + engine + '\n};\n' +
    'window.ASTERIA_CORE.call(window);\n';
}
module.exports = build;
if (require.main === module) {
  fs.writeFileSync(path.join(root, 'js', 'core.js'), build());
  console.log('js/core.js written');
}
