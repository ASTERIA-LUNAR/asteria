#!/usr/bin/env node
/* One-year illumination / Earth-visibility statistics for south-polar sites, with LOLA
 * terrain horizon masks vs smooth Moon. Writes data/illumination.js and prints a table.
 * Usage: node tests/illumination.js */
'use strict';
const fs = require('fs'), path = require('path');
const E = require('../js/engine.js');
global.window = {};
require('../data/sites.js');
const dir = path.join(__dirname, '..', 'data', 'horizons');
for (const f of fs.readdirSync(dir)) if (f !== 'index.js') require(path.join(dir, f));
const start = new Date('2027-01-01T00:00:00Z'), end = new Date('2028-01-01T00:00:00Z');
const STEP = 30; // minutes
const rows = [];
for (const s of window.LUNA_SITES) {
  const hz = window.LUNA_HORIZONS[s.id];
  if (!hz) continue;
  const site = { lat: s.lat, lon: s.lon };
  const terr = E.stats(E.series(site, start, end, STEP, hz.elevations));
  const smooth = E.stats(E.series(site, start, end, STEP, null));
  rows.push({ id: s.id, name: s.name, lat: s.lat, lon: s.lon, siteHeight_m: hz.siteHeight_m,
    sunTerrain: terr.pctSun, sunSmooth: smooth.pctSun, earthTerrain: terr.pctEarth, earthSmooth: smooth.pctEarth,
    bothTerrain: terr.pctBoth, longestDarkH: terr.longestDarkH, longestBlackoutH: terr.longestBlackoutH });
}
const out = { period: '2027-01-01 to 2028-01-01 UTC', stepMin: STEP, observerHeight_m: 2, rows };
fs.writeFileSync(path.join(__dirname, '..', 'data', 'illumination.js'),
  '// Generated by tests/illumination.js\nwindow.LUNA_ILLUMINATION = ' + JSON.stringify(out, null, 1) + ';\n');
console.log('site                 h(m)   sun% terrain  sun% smooth  earth% terrain  both%  longest dark (h)');
for (const r of rows) console.log(r.id.padEnd(20), String(Math.round(r.siteHeight_m)).padStart(6),
  r.sunTerrain.toFixed(1).padStart(10), r.sunSmooth.toFixed(1).padStart(12), r.earthTerrain.toFixed(1).padStart(14),
  r.bothTerrain.toFixed(1).padStart(7), r.longestDarkH.toFixed(0).padStart(10));
