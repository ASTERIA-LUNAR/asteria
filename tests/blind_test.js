/* Blind test against JPL Horizons.
 *   node tests/blind_test.js --new   picks 5 NEW random cases (random curated south-pole site with a terrain
 *                                    horizon, random whole-minute UTC time in 2026-2030, chosen with
 *                                    crypto.randomInt), refuses any query already in tests/horizons_cache,
 *                                    fetches Sun and Earth az/el fresh from the Horizons API, and writes the
 *                                    case list to data/blind_test.js.
 *   node tests/blind_test.js         re-evaluates the stored cases offline from the cache.
 * The comparison itself (engine vs Horizons, same tolerances as Part A) is also run by tests/validate.js,
 * which puts it in VALIDATION_REPORT.md and on the Validation page. */
'use strict';
const fs = require('fs'), path = require('path'), crypto = require('crypto');
const E = require('../js/engine.js');
const HZ = require('./horizons_api.js');
const ROOT = path.join(__dirname, '..'), OUT = path.join(ROOT, 'data', 'blind_test.js');

function loadCases() {
  if (!fs.existsSync(OUT)) return null;
  const w = {}; new Function('window', fs.readFileSync(OUT, 'utf8'))(w); return w.LUNA_BLIND;
}
async function evaluate(cases) {
  const rows = [];
  for (const c of cases) {
    const ours = E.sunEarthAt({ lat: c.lat, lon: c.lon, h_km: 0 }, new Date(c.date));
    for (const [body, cmd] of [['Sun', "'10'"], ['Earth', "'399'"]]) {
      const params = { COMMAND: cmd, SITE_COORD: HZ.siteCoord(c), TLIST: `'${HZ.fmtH(new Date(c.date))}'` };
      const h = await HZ.horizons(params), row = HZ.parseRows(h.text)[0], o = body === 'Sun' ? ours.sun : ours.earth;
      const dEl = o.el - row.el, dAz = HZ.azDiff(o.az, row.az);
      const azTol = row.el > 80 ? 0.2 / Math.cos(row.el * Math.PI / 180) : 0.2;
      rows.push({ siteId: c.siteId, name: c.name, lat: c.lat, lon: c.lon, date: c.date, body, oursAz: o.az, oursEl: o.el, hzAz: row.az, hzEl: row.el, dAz, dEl,
        pass: Math.abs(dEl) < 0.1 && Math.abs(dAz) < azTol, url: h.url, cacheFile: path.relative(ROOT, h.file).replace(/\\/g, '/') });
    }
  }
  return rows;
}
module.exports = { loadCases, evaluate };

if (require.main === module) (async () => {
  let B = loadCases();
  if (process.argv.includes('--new')) {
    global.window = {}; require('../data/sites.js');
    const hzIds = fs.readdirSync(path.join(ROOT, 'data', 'horizons')).filter(f => f !== 'index.js').map(f => f.replace('.js', ''));
    const pool = window.LUNA_SITES.filter(s => hzIds.includes(s.id));
    const t0 = Date.UTC(2026, 0, 1), minutes = (Date.UTC(2031, 0, 1) - t0) / 60000;
    const cases = [];
    while (cases.length < 5) {
      const s = pool[crypto.randomInt(pool.length)];
      const date = new Date(t0 + crypto.randomInt(minutes) * 60000).toISOString().replace(':00.000Z', 'Z');
      const keys = ["'10'", "'399'"].map(cmd => ({ COMMAND: cmd, SITE_COORD: HZ.siteCoord(s), TLIST: `'${HZ.fmtH(new Date(date))}'` }));
      if (keys.some(k => HZ.isCached(k)) || cases.some(c => c.siteId === s.id && c.date === date)) continue;   // must be new
      cases.push({ siteId: s.id, name: s.name, lat: s.lat, lon: s.lon, date });
    }
    for (const c of cases) {           // fetch fresh, record when
      for (const cmd of ["'10'", "'399'"]) { const r = await HZ.horizons({ COMMAND: cmd, SITE_COORD: HZ.siteCoord(c), TLIST: `'${HZ.fmtH(new Date(c.date))}'` }); if (r.cached) throw new Error('not a fresh fetch'); }
      c.fetchedAt = new Date().toISOString();
    }
    B = { generated: new Date().toISOString(), selection: 'crypto.randomInt: site uniformly from the curated south-pole sites with terrain horizons; time uniformly over whole minutes 2026-01-01..2030-12-31 UTC; queries already in tests/horizons_cache were rejected; every response fetched fresh from the Horizons API', cases };
    fs.writeFileSync(OUT, '// Generated by tests/blind_test.js --new (cases only; comparison recomputed by tests/validate.js)\nwindow.LUNA_BLIND = ' + JSON.stringify(B, null, 1) + ';\n');
  }
  if (!B) { console.log('No blind cases yet: run node tests/blind_test.js --new'); process.exit(1); }
  const rows = await evaluate(B.cases);
  for (const r of rows) console.log(`${r.pass ? 'PASS' : 'FAIL'} ${r.name.padEnd(48)} ${r.date} ${r.body.padEnd(5)} az ${r.oursAz.toFixed(4)} vs ${r.hzAz.toFixed(4)} (d ${r.dAz.toFixed(4)})  el ${r.oursEl.toFixed(4)} vs ${r.hzEl.toFixed(4)} (d ${r.dEl.toFixed(4)})`);
  const mx = k => Math.max(...rows.map(r => Math.abs(r[k])));
  console.log(`Blind test: ${rows.filter(r => r.pass).length}/${rows.length} pass; max |dEl| ${mx('dEl').toFixed(4)} deg, max |dAz| ${mx('dAz').toFixed(4)} deg`);
  process.exit(rows.every(r => r.pass) ? 0 : 1);
})().catch(e => { console.error(e); process.exit(2); });
